// Writes spec/emoji.json: the bundled emoji set of lab's EmojiPicker, read from upstream's
// generated packages/lab/src/EmojiPicker/emojiData.ts (emojibase-data, built from Unicode
// CLDR): every CLDR group but the component group, in CLDR order, each emoji as
// [character, CLDR name, keywords joined by spaces]. `cargo xtask codegen` turns it into
// crates/rustryx-lab/src/emoji_picker/generated/emoji_data.rs.
//
//   node tools/export/export-emoji.mjs [path/to/Astryx]   (also run by export-all.mjs)

import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {astryxRoot, importTs} from './lib/astryx.mjs';
import {stableStringify} from './lib/values.mjs';

const FILE = 'packages/lab/src/EmojiPicker/emojiData.ts';

export async function exportEmoji(root, specDir, warnings) {
  const file = path.join(root, FILE);
  const source = fs.readFileSync(file, 'utf8');
  // The generator and the data release, from the file's own header.
  const generated = /@generated by (.+?) from\s*\n?\s*\/\/\s*(.+?)\. Do not edit/s.exec(source);
  const {EMOJI_GROUPS} = await importTs(root, file);
  if (!Array.isArray(EMOJI_GROUPS) || EMOJI_GROUPS.length === 0) {
    warnings.push(`${FILE}: no EMOJI_GROUPS`);
    return;
  }
  const groups = EMOJI_GROUPS.map(group => ({
    name: group.name,
    emojis: group.emojis.map(([emoji, name, keywords]) => [emoji, name, keywords]),
  }));
  const count = groups.reduce((n, g) => n + g.emojis.length, 0);
  fs.writeFileSync(
    path.join(specDir, 'emoji.json'),
    stableStringify({
      source: generated ? generated[2].replace(/\s+/g, ' ').trim() : 'unknown',
      groups,
    }),
  );
  console.log(`wrote spec/emoji.json (${groups.length} groups, ${count} emoji)`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
  const root = astryxRoot(process.argv[2] ?? path.join(repoRoot, '..', 'Astryx'));
  const warnings = [];
  await exportEmoji(root, path.join(repoRoot, 'spec'), warnings);
  for (const warning of warnings) console.warn(`warning: ${warning}`);
}

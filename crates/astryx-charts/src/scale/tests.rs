#[test]
fn linear_nice_matches_d3() {
    // (domain, count, scaleLinear().domain(domain).nice(count).domain())
    let cases: &[([f64; 2], f64, [f64; 2])] = &[
        ([0.201479, 0.996679], 10.0, [0.2, 1.0]),
        ([0.996679, 0.201479], 10.0, [1.0, 0.2]),
        ([1.1, 10.9], 5.0, [0.0, 12.0]),
        ([-123.0, 456.0], 10.0, [-150.0, 500.0]),
        ([0.0, 0.0], 10.0, [0.0, 0.0]),
        ([INF, 1.0], 10.0, [INF, 1.0]),
        ([NAN, 1.0], 10.0, [NAN, 1.0]),
        ([1.1, 10.9], 0.0, [1.1, 10.9]),
        ([1e-30, 3e-30], 3.0, [9.999999999999999e-31, 3e-30]),
        ([3.0, 3.000000000000001], 10.0, [3.0, 3.000000000000001]),
        (
            [4.274860680389261e-21, 4.2757031760994935e-21],
            2.0,
            [4.274860680389261e-21, 4.2757031760994935e-21],
        ),
    ];
    for &(domain, count, want) in cases {
        let scale = LinearScale::new()
            .domain(domain[0], domain[1])
            .nice_count(count);
        assert_same(&scale.get_domain(), &want);
    }
    let scale = LinearScale::new().domain(0.201479, 0.996679).nice();
    assert_same(&scale.get_domain(), &[0.2, 1.]);
}


//! The scales and number formats against d3's own output: every expected value was
//! produced by running d3-array 3.2.4, d3-scale 4.0.2 and d3-format 3.1.2 under Node.

use super::*;

const NAN: f64 = f64::NAN;
const INF: f64 = f64::INFINITY;

/// The same double, NaN equal to NaN and -0 apart from 0.
fn same(a: f64, b: f64) -> bool {
    (a.is_nan() && b.is_nan()) || a.to_bits() == b.to_bits()
}

/// A linear scale case: domain, range, clamp, inputs, outputs, range inputs, inverted.
type LinearCase<'a> = (
    [f64; 2],
    [f64; 2],
    bool,
    &'a [f64],
    &'a [f64],
    &'a [f64],
    &'a [f64],
);

/// A tick format case: domain, count, specifier, values, formatted values.
type TickFormatCase<'a> = ([f64; 2], f64, Option<&'a str>, &'a [f64], &'a [&'a str]);

/// A band scale case: the scale, its domain, bandwidth, step, bands.
type BandCase<'a> = (BandScale, &'a [&'a str], f64, f64, &'a [Option<f64>]);

#[track_caller]
fn assert_same(got: &[f64], want: &[f64]) {
    assert!(
        got.len() == want.len() && got.iter().zip(want).all(|(a, b)| same(*a, *b)),
        "{got:?} != {want:?}"
    );
}


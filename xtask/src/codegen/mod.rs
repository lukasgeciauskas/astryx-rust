//! `cargo xtask codegen [--check]`: generates Rust sources from `spec/`.
//!
//! - `crates/astryx-theme/src/generated/tokens.rs`: the typed token surface.
//! - `crates/astryx-theme/src/generated/default_theme.rs`: core's defaults.
//! - `crates/astryx-themes/src/generated/*.rs`: one module per theme.
//! - `crates/astryx-icons/src/generated.rs`: the embedded icon files.
//! - `crates/astryx-i18n/src/generated/catalogs.rs`: message catalogs.
//! - `crates/astryx-i18n/src/generated/cldr.rs`: CLDR tables for dates.
//! - `docs/theme-overrides-todo.md`: overrides that need a hand port.
//!
//! `--check` writes nothing and fails when any file differs from what it
//! would generate.

mod cldr;
mod literal;
mod locales;
mod themes;
mod tokens;

use std::collections::BTreeMap;
use std::fs;
use std::io::Write as _;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

use anyhow::{Context, Result, bail};
use serde_json::Value;

use crate::workspace_root;

const HEADER: &str = "// @generated by `cargo xtask codegen` from spec/. Do not edit.\n// Regenerate with `cargo xtask codegen`; see UPSTREAM.md.\n\n";

pub fn run(args: &[String]) -> Result<()> {
    let check = args.iter().any(|a| a == "--check");
    let root = workspace_root();
    let files = generate(&root)?;

    let mut stale = Vec::new();
    for (path, contents) in &files {
        let full = root.join(path);
        let current = fs::read_to_string(&full)
            .unwrap_or_default()
            .replace("\r\n", "\n");
        if current == *contents {
            continue;
        }
        if check {
            stale.push(path.display().to_string());
        } else {
            fs::create_dir_all(full.parent().unwrap())?;
            fs::write(&full, contents)?;
            println!("wrote {}", path.display());
        }
    }
    if !stale.is_empty() {
        bail!(
            "generated files are out of date: {}\nrun `cargo xtask codegen`",
            stale.join(", ")
        );
    }
    if check {
        println!("generated files are up to date");
    }
    Ok(())
}

fn read_json(path: &Path) -> Result<Value> {
    let text = fs::read_to_string(path).with_context(|| format!("reading {}", path.display()))?;
    serde_json::from_str(&text).with_context(|| format!("parsing {}", path.display()))
}

fn generate(root: &Path) -> Result<Vec<(PathBuf, String)>> {
    let spec = root.join("spec");
    let mut themes = BTreeMap::new();
    for entry in fs::read_dir(spec.join("themes"))? {
        let path = entry?.path();
        if path.extension().is_some_and(|e| e == "json") {
            let theme = read_json(&path)?;
            let name = theme["name"]
                .as_str()
                .context("theme without name")?
                .to_string();
            themes.insert(name, theme);
        }
    }
    let default = themes
        .remove("default")
        .context("spec/themes/default.json is missing")?;
    let icons = read_json(&spec.join("icons.json"))?;
    let surface = tokens::surface(default["tokens"]["light"].as_object().context("tokens")?)?;

    let mut files = Vec::new();
    files.push((
        PathBuf::from("crates/astryx-theme/src/generated/tokens.rs"),
        rustfmt(&format!(
            "{HEADER}use crate::generated_prelude::*;\n\n{}",
            tokens::render_types(&surface)?
        ))?,
    ));

    let mut default_module = format!("{HEADER}use crate::generated_prelude::*;\n\n");
    for mode in ["light", "dark"] {
        let values = default["tokens"][mode].as_object().context("tokens")?;
        default_module.push_str(&format!(
            "/// Core's default tokens in {mode} mode.\npub const {}: Tokens = {};\n\n",
            mode.to_uppercase(),
            tokens::render_value(&surface, values, values)?
        ));
    }
    files.push((
        PathBuf::from("crates/astryx-theme/src/generated/default_theme.rs"),
        rustfmt(&default_module)?,
    ));

    let lucide = icons["lucide"].as_object().context("icons.lucide")?;
    let mut todo = BTreeMap::new();
    let mut mod_rs = String::from(HEADER);
    for (name, theme) in &themes {
        let output = themes::render_theme(theme, &surface, &default, lucide)
            .with_context(|| format!("theme {name}"))?;
        todo.insert(name.clone(), output.todo);
        files.push((
            PathBuf::from(format!("crates/astryx-themes/src/generated/{name}.rs")),
            rustfmt(&format!(
                "{HEADER}use astryx_theme::generated_prelude::*;\n\n{}",
                output.module
            ))?,
        ));
        mod_rs.push_str(&format!(
            "#[cfg(feature = \"{name}\")]\n#[rustfmt::skip]\npub mod {name};\n"
        ));
    }
    mod_rs.push_str("\n/// Every theme compiled in through cargo features.\npub fn all() -> Vec<astryx_theme::Theme> {\n    vec![\n");
    for name in themes.keys() {
        mod_rs.push_str(&format!(
            "        #[cfg(feature = \"{name}\")]\n        {name}::theme(),\n"
        ));
    }
    mod_rs.push_str("    ]\n}\n");
    files.push((
        PathBuf::from("crates/astryx-themes/src/generated/mod.rs"),
        rustfmt(&mod_rs)?,
    ));

    files.push((
        PathBuf::from("crates/astryx-icons/src/generated.rs"),
        rustfmt(&render_icons(root, &icons)?)?,
    ));
    files.push((
        PathBuf::from("crates/astryx-i18n/src/generated/catalogs.rs"),
        rustfmt(&locales::render(&spec)?)?,
    ));
    files.push((
        PathBuf::from("crates/astryx-i18n/src/generated/cldr.rs"),
        rustfmt(&cldr::render(&spec)?)?,
    ));
    files.push((
        PathBuf::from("docs/theme-overrides-todo.md"),
        themes::render_todo(&todo),
    ));
    Ok(files)
}

fn render_icons(root: &Path, icons: &Value) -> Result<String> {
    let mut out = format!(
        "{HEADER}/// Core's fallback icon names, drawn when a theme maps no icon.\npub const CORE_ICONS: &[&str] = &[\n"
    );
    let core: Vec<&str> = icons["core"]
        .as_array()
        .context("icons.core")?
        .iter()
        .filter_map(Value::as_str)
        .collect();
    for name in &core {
        out.push_str(&format!("    {name:?},\n"));
    }
    out.push_str("];\n\n/// Every embedded icon file, by asset path.\npub const FILES: &[(&str, &[u8])] = &[\n");
    let mut files = Vec::new();
    for set in ["core", "lucide"] {
        let dir = root.join("crates/astryx-icons/assets").join(set);
        for entry in fs::read_dir(&dir).with_context(|| format!("reading {}", dir.display()))? {
            let file = entry?.file_name().to_string_lossy().to_string();
            if file.ends_with(".svg") {
                files.push(format!("icons/{set}/{file}"));
            }
        }
    }
    files.sort();
    for path in files {
        let source = path.trim_start_matches("icons/");
        out.push_str(&format!(
            "    ({path:?}, include_bytes!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/assets/{source}\"))),\n"
        ));
    }
    out.push_str("];\n");
    Ok(out)
}

/// Formats generated source with rustfmt, so `--check` compares like with like.
fn rustfmt(source: &str) -> Result<String> {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .context("failed to start rustfmt")?;
    child.stdin.take().unwrap().write_all(source.as_bytes())?;
    let output = child.wait_with_output()?;
    if !output.status.success() {
        bail!(
            "rustfmt failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }
    Ok(String::from_utf8(output.stdout)?.replace("\r\n", "\n"))
}
